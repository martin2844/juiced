"""PNG (8-bit RGB/RGBA, not interlaced) to the game's uncompressed .ddt (A8R8G8B8, one level).

png_to_ddt.py in.png out.ddt
png_to_ddt.py --inc out.inc name=in.png ...   C arrays of the .ddt files zlib-compressed (kName)
"""
import struct
import sys
import zlib


def read_png(path):
    data = open(path, 'rb').read()
    assert data[:8] == b'\x89PNG\r\n\x1a\n', 'not a PNG'
    pos, idat = 8, b''
    while pos < len(data):
        size, kind = struct.unpack('>I4s', data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + size]
        if kind == b'IHDR':
            w, h, depth, colour, _, _, interlace = struct.unpack('>IIBBBBB', body)
            assert depth == 8 and colour in (2, 6) and interlace == 0, 'unsupported PNG'
        elif kind == b'IDAT':
            idat += body
        pos += 12 + size
    bpp = 4 if colour == 6 else 3
    raw, stride, rows, prev = zlib.decompress(idat), w * bpp, [], bytearray(w * bpp)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b, c = prev[i], prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line)
        prev = line
    return w, h, bpp, rows


def ddt(path):
    w, h, bpp, rows = read_png(path)
    out = bytearray(struct.pack('<11I', 21, w, h, 1, 2, 2, 0, 3, 3, 0, 1))
    for line in rows:
        for x in range(w):
            r, g, b = line[x * bpp:x * bpp + 3]
            out += bytes((b, g, r, line[x * bpp + 3] if bpp == 4 else 255))
    return bytes(out)


if sys.argv[1] == '--inc':
    lines = ['// Generated by tools/png_to_ddt.py --inc: zlib-compressed .ddt pictures.']
    for arg in sys.argv[3:]:
        name, path = arg.split('=', 1)
        packed = zlib.compress(ddt(path), 9)
        lines.append(f'constexpr unsigned char k{name}[] = {{')
        for i in range(0, len(packed), 24):
            lines.append('    ' + ', '.join(f'0x{b:02X}' for b in packed[i:i + 24]) + ',')
        lines.append('};')
    open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')
else:
    open(sys.argv[2], 'wb').write(ddt(sys.argv[1]))
