// Unit tests: Inflate.

#include "Framework/Test.h"

#include "Core/Formats/DatArchive.h"
#include "Core/Formats/Inflate.h"

#include <format>
#include <string>
#include <vector>

namespace {

using oj::test::check;

}  // namespace

// The archives: zlib streams of each kind of deflate block (stored, fixed, dynamic) inflated, a broken sum
// refused; the name hash of 0x004FCF80 (scripts.dat holds cardefs.txt under 1946464662).
OJ_UNIT_TEST(Inflate, DeflateBlocks) {
    const std::vector<uint8_t> stored = {0x78, 0x01, 0x01, 0x1D, 0x00, 0xE2, 0xFF, 0x4F, 0x70, 0x65, 0x6E, 0x4A,
                                         0x75, 0x69, 0x63, 0x65, 0x20, 0x72, 0x65, 0x61, 0x64, 0x73, 0x20, 0x74,
                                         0x68, 0x65, 0x20, 0x61, 0x72, 0x63, 0x68, 0x69, 0x76, 0x65, 0x73, 0x2E,
                                         0xA1, 0x6E, 0x0A, 0xB6};
    const std::vector<uint8_t> fixed = {0x78, 0xDA, 0x4B, 0x4C, 0x4A, 0x4E, 0x44, 0x45, 0x0A, 0x19, 0xA9,
                                        0x39, 0x39, 0xF9, 0xC8, 0x24, 0x00, 0xF9, 0xF3, 0x0D, 0x81};
    const std::vector<uint8_t> dynamic = {
        0x78, 0xDA, 0xED, 0xD1, 0xBB, 0x0D, 0x80, 0x30, 0x10, 0x83, 0xE1, 0x55, 0x3C, 0x00, 0x05, 0xEF, 0x86,
        0x69, 0x4E, 0xE4, 0x20, 0x91, 0x42, 0x22, 0x25, 0x08, 0xD6, 0x47, 0xC0, 0x06, 0x57, 0xBB, 0xB3, 0x8B,
        0xAF, 0xFA, 0x63, 0x48, 0x8A, 0x16, 0x79, 0xC3, 0xE9, 0x15, 0x52, 0x56, 0x1F, 0x2E, 0x6D, 0xBE, 0x53,
        0xE5, 0x50, 0xDC, 0xB9, 0xB8, 0x0A, 0xD9, 0x25, 0x24, 0x48, 0x72, 0xFF, 0x5A, 0x10, 0x5F, 0xD6, 0xD9,
        0x58, 0x6F, 0x63, 0x83, 0x8D, 0x8D, 0x36, 0x36, 0xD9, 0xD8, 0x6C, 0x63, 0x0C, 0xC0, 0x00, 0x0C, 0xC0,
        0x00, 0x0C, 0xC0, 0x00, 0x0C, 0xF0, 0xB2, 0x07, 0x3C, 0x2A, 0xF3, 0x92};
    auto text = [](const std::vector<std::byte>& b) {
        return std::string(reinterpret_cast<const char*>(b.data()), b.size());
    };
    std::vector<std::byte> a, b, c, broken;
    std::string lines;
    for (int i = 0; i < 40; ++i) {
        lines += std::format("line {} of the archive, the same words again and again; ", i % 7);
    }
    std::vector<uint8_t> bad = fixed;
    bad.back() ^= 1;
    const bool inflated = oj::inflateZlib(stored.data(), stored.size(), a) &&
                          text(a) == "OpenJuice reads the archives." &&
                          oj::inflateZlib(fixed.data(), fixed.size(), b) &&
                          text(b) == "abcabcabcabcabcabc hello hello hello" &&
                          oj::inflateZlib(dynamic.data(), dynamic.size(), c) && text(c) == lines &&
                          !oj::inflateZlib(bad.data(), bad.size(), broken);
    check(inflated && oj::datHash("cardefs.txt") == 1946464662u && oj::datHash("") == 0,
          "archives: stored, fixed and dynamic deflate blocks, the Adler sum, the names' hash");
}
